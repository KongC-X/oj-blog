// ===== 解析本地md =====

function parseLocalMd(filePath) {
    const content = fs.readFileSync(filePath, 'utf-8');
    const entries = [];
    const codeBlockRegex = /```(?:[Cc]\+\+|cpp|[Cc])\n([\s\S]*?)```/g;
    const imageRegex = /!\[([^\]]*)\]\(([^)]+)\)/g;
    
    const images = [];
    let m;
    while ((m = imageRegex.exec(content)) !== null) {
        images.push({ alt: m[1], path: m[2], start: m.index });
    }
    
    while ((m = codeBlockRegex.exec(content)) !== null) {
        const code = m[1].trim();
        let bestImage = null;
        for (const img of images) {
            if (img.start < m.index && (!bestImage || img.start > bestImage.start)) {
                bestImage = img;
            }
        }
        entries.push({ image: bestImage, code });
    }
    return entries;
}

// ===== 写入代码 =====

function writeCodeToProblem(problemId, code, source, label) {
    const filePath = path.join(SOLUTIONS_DIR, `${problemId}.md`);
    if (!fs.existsSync(filePath)) return { ok: false, msg: `文件不存在: ${problemId}.md` };
    
    let content = fs.readFileSync(filePath, 'utf-8');
    
    // 检查是否已有完全相同的代码（用第5-7行的独特部分判断）
    const codeLines = code.trim().split('\n').filter(l => l.trim() && !l.trim().startsWith('#') && !l.trim().startsWith('using'));
    const signature = codeLines.slice(0, 3).join('\n');
    if (content.includes(signature)) {
        return { ok: false, msg: `已有相同题解: ${problemId}` };
    }
    
    if (content.includes('## 题解')) {
        // 追加第二种解法
        const codeSection = `\n\n## 题解（${label || '解法二'}）\n\n\`\`\`cpp\n${code}\n\`\`\`\n\n`;
        content = content.trimEnd() + codeSection;
        fs.writeFileSync(filePath, content, 'utf-8');
        return { ok: true, msg: `${problemId}.md 已追加${label || '第二种解法'}` };
    }
    
    const codeSection = `\n\n## 题解\n\n\`\`\`cpp\n${code}\n\`\`\`\n\n`;
    content = content.trimEnd() + codeSection;
    
    fs.writeFileSync(filePath, content, 'utf-8');
    return { ok: true, msg: `${problemId}.md 已写入` };
}

// ===== 主流程 =====

function main() {
    const args = process.argv.slice(2);
    const writeMode = args.includes('--write');
    const allMode = args.includes('--all');
    
    console.log('═══════════════════════════════════════════════');
    console.log('  OJ 题解站 - 代码批量导入工具 v3');
    console.log('═══════════════════════════════════════════════');
    console.log(`  模式: ${writeMode ? '📝 写入' : '🔍 预览'}（加 --write 执行写入）\n`);
    
    // 确定要处理的文件
    const filesToProcess = [];
    if (allMode) {
        const mdFiles = fs.readdirSync(COURSE_DIR).filter(f => f.endsWith('.md') && f.includes('练习题'));
        for (const f of mdFiles) {
            if (MAPPINGS[f]) filesToProcess.push({ name: f, path: path.join(COURSE_DIR, f) });
            else filesToProcess.push({ name: f, path: path.join(COURSE_DIR, f), noMapping: true });
        }
    } else {
        const fileArgs = args.filter(a => !a.startsWith('--'));
        if (fileArgs.length === 0) {
            // 默认处理有映射的文件
            for (const [name] of Object.entries(MAPPINGS)) {
                filesToProcess.push({ name, path: path.join(COURSE_DIR, name) });
            }
        } else {
            for (const f of fileArgs) {
                const fullPath = f.startsWith('/') ? f : path.resolve(f);
                const basename = path.basename(fullPath);
                filesToProcess.push({ name: basename, path: fullPath });
            }
        }
    }
    
    let totalSuccess = 0, totalSkip = 0, totalFail = 0, totalNoMatch = 0;
    
    for (const file of filesToProcess) {
        const mapping = MAPPINGS[file.name];
        
        console.log(`${'─'.repeat(60)}`);
        console.log(`📁 ${file.name}`);
        if (file.noMapping) {
            console.log('   ⚠️  无映射表，跳过（需手动建立映射）');
            continue;
        }
        console.log(`${'─'.repeat(60)}`);
        
        const entries = parseLocalMd(file.path);
        console.log(`  代码块: ${entries.length} 个\n`);
        
        for (const [idx, problemId, confidence, note, label] of mapping) {
            if (idx >= entries.length) {
                console.log(`  ⚠️  #${idx + 1} 映射超出范围（代码块只有${entries.length}个）`);
                continue;
            }
            
            const entry = entries[idx];
            const confIcon = confidence === 'high' ? '🟢' : confidence === 'medium' ? '🟡' : '🔴';
            
            if (problemId === null) {
                console.log(`  ${confIcon} #${idx + 1} → ❌ 未匹配: ${note}`);
                console.log(`     代码: ${entry.code.substring(0, 100).replace(/\n/g, ' ')}...`);
                totalNoMatch++;
                continue;
            }
            
            // 检查题目文件是否存在
            const problemFile = path.join(SOLUTIONS_DIR, `${problemId}.md`);
            if (!fs.existsSync(problemFile)) {
                console.log(`  ${confIcon} #${idx + 1} → ⚠️  ${problemId} 题目文件不存在`);
                totalFail++;
                continue;
            }
            
            // 读取题目标题
            const probContent = fs.readFileSync(problemFile, 'utf-8');
            const titleMatch = probContent.match(/title:\s*"([^"]+)"/);
            const title = titleMatch ? titleMatch[1] : '未知';
            const hasExistingCode = probContent.includes('## 题解');
            const codeLines = entry.code.trim().split('\n').filter(l => l.trim() && !l.trim().startsWith('#') && !l.trim().startsWith('using'));
            const signature = codeLines.slice(0, 3).join('\n');
            const hasDuplicate = probContent.includes(signature);
            
            if (hasDuplicate) {
                console.log(`  ${confIcon} #${idx + 1} → ${problemId} ${title} (已有相同代码，跳过)`);
                totalSkip++;
                continue;
            }
            
            if (writeMode) {
                const result = writeCodeToProblem(problemId, entry.code, file.name, label);
                if (result.ok) {
                    console.log(`  ${confIcon} #${idx + 1} → ${problemId} ${title} ✅ 已写入`);
                    totalSuccess++;
                } else {
                    console.log(`  ${confIcon} #${idx + 1} → ${problemId} ${title} ⚠️ ${result.msg}`);
                    totalFail++;
                }
            } else {
                console.log(`  ${confIcon} #${idx + 1} → ${problemId} ${title}`);
                console.log(`     ${note}`);
                totalSuccess++; // 预览模式下也算匹配成功
            }
        }
    }
    
    console.log(`\n${'═'.repeat(60)}`);
    console.log(`  📊 结果摘要`);
    console.log(`${'═'.repeat(60)}`);
    if (writeMode) {
        console.log(`  ✅ 成功写入: ${totalSuccess}`);
        console.log(`  ⏭️  已有跳过: ${totalSkip}`);
        console.log(`  ❌ 失败: ${totalFail}`);
    } else {
        console.log(`  ✅ 可匹配: ${totalSuccess}`);
    }
    console.log(`  ❓ 未匹配: ${totalNoMatch}`);
    if (!writeMode && totalSuccess > 0) {
        console.log(`\n  💡 加 --write 参数执行实际写入`);
    }
}

main();
